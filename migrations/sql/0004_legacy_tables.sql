CREATE TABLE curve_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    curve_date DATE NOT NULL,
    quote_time TIME WITHOUT TIME ZONE NOT NULL,
    tenor NUMERIC(12, 6) NOT NULL,
    yield_rate NUMERIC(18, 10) NOT NULL,
    discount_factor NUMERIC(28, 18) NOT NULL,
    etl_run_id UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    is_interpolated BOOLEAN DEFAULT false NOT NULL,
    is_extrapolated BOOLEAN DEFAULT false NOT NULL,
    is_deleted BOOLEAN DEFAULT false NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_curve_points_snapshot_tenor UNIQUE (curve_date, quote_time, tenor),
    CONSTRAINT ck_curve_points_tenor CHECK (tenor > 0 AND tenor < 'Infinity'::numeric),
    CONSTRAINT ck_curve_points_yield CHECK (yield_rate > '-Infinity'::numeric AND yield_rate < 'Infinity'::numeric),
    CONSTRAINT ck_curve_points_discount CHECK (discount_factor > 0 AND discount_factor < 'Infinity'::numeric),
    CONSTRAINT fk_curve_points_etl_run FOREIGN KEY(etl_run_id) REFERENCES etl_runs (id) ON DELETE RESTRICT
);
-- statement-break
CREATE INDEX ix_curve_points_etl_run_id ON curve_points (etl_run_id);
-- statement-break
CREATE TABLE stress_curves (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    curve_point_id BIGINT NOT NULL,
    stress_shock_id BIGINT NOT NULL,
    stressed_yield NUMERIC(18, 10) NOT NULL,
    discount_factor NUMERIC(28, 18) NOT NULL,
    etl_run_id UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_stress_curves_point_shock UNIQUE (curve_point_id, stress_shock_id),
    CONSTRAINT ck_stress_curves_yield CHECK (stressed_yield > '-Infinity'::numeric AND stressed_yield < 'Infinity'::numeric),
    CONSTRAINT ck_stress_curves_discount CHECK (discount_factor > 0 AND discount_factor < 'Infinity'::numeric),
    CONSTRAINT fk_stress_curves_point FOREIGN KEY(curve_point_id) REFERENCES curve_points (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stress_curves_shock FOREIGN KEY(stress_shock_id) REFERENCES stress_shocks (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stress_curves_etl_run FOREIGN KEY(etl_run_id) REFERENCES etl_runs (id) ON DELETE RESTRICT
);
-- statement-break
CREATE INDEX ix_stress_curves_etl_run_id ON stress_curves (etl_run_id);
-- statement-break
CREATE INDEX ix_stress_curves_shock_point ON stress_curves (stress_shock_id, curve_point_id);
