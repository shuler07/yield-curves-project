CREATE TABLE stress_curves (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curve_point_id BIGINT NOT NULL,
    stress_shock_id BIGINT NOT NULL,
    stressed_yield NUMERIC(18, 10) NOT NULL,
    discount_factor NUMERIC(28, 18) NOT NULL,
    discount_convention VARCHAR(100) NOT NULL,
    etl_run_id UUID NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT fk_stress_curves_point FOREIGN KEY (curve_point_id)
        REFERENCES curve_points(id) ON DELETE RESTRICT,
    CONSTRAINT fk_stress_curves_shock FOREIGN KEY (stress_shock_id)
        REFERENCES stress_shocks(id) ON DELETE RESTRICT,
    CONSTRAINT fk_stress_curves_etl_run FOREIGN KEY (etl_run_id)
        REFERENCES etl_runs(id) ON DELETE RESTRICT,
    CONSTRAINT uq_stress_curves_point_shock UNIQUE (curve_point_id, stress_shock_id),
    CONSTRAINT ck_stress_curves_yield CHECK (
        stressed_yield > '-Infinity'::numeric AND stressed_yield < 'Infinity'::numeric
    ),
    CONSTRAINT ck_stress_curves_discount CHECK (
        discount_factor > 0 AND discount_factor < 'Infinity'::numeric
    ),
    CONSTRAINT ck_stress_curves_convention CHECK (length(btrim(discount_convention)) > 0)
);
-- statement-break
CREATE INDEX ix_stress_curves_shock_point ON stress_curves (stress_shock_id, curve_point_id);
-- statement-break
CREATE INDEX ix_stress_curves_etl_run_id ON stress_curves (etl_run_id);
