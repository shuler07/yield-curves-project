CREATE FUNCTION reject_stress_shock_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Scenario parameter sets are immutable; insert a new version'
        USING ERRCODE = '23514';
END;
$$;
-- statement-break
CREATE TRIGGER stress_shocks_immutable
BEFORE UPDATE ON stress_shocks
FOR EACH ROW EXECUTE FUNCTION reject_stress_shock_update();
