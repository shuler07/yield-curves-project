CREATE TABLE curve_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curve_date DATE NOT NULL,
    quote_time TIME WITHOUT TIME ZONE NOT NULL,
    tenor NUMERIC(12, 6) NOT NULL,
    yield_rate NUMERIC(18, 10) NOT NULL,
    discount_factor NUMERIC(28, 18) NOT NULL,
    discount_convention VARCHAR(100) NOT NULL,
    etl_run_id UUID NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT fk_curve_points_etl_run FOREIGN KEY (etl_run_id)
        REFERENCES etl_runs(id) ON DELETE RESTRICT,
    CONSTRAINT uq_curve_points_snapshot_tenor UNIQUE (curve_date, quote_time, tenor),
    CONSTRAINT ck_curve_points_tenor CHECK (tenor > 0 AND tenor < 'Infinity'::numeric),
    CONSTRAINT ck_curve_points_yield CHECK (
        yield_rate > '-Infinity'::numeric AND yield_rate < 'Infinity'::numeric
    ),
    CONSTRAINT ck_curve_points_discount CHECK (
        discount_factor > 0 AND discount_factor < 'Infinity'::numeric
    ),
    CONSTRAINT ck_curve_points_convention CHECK (length(btrim(discount_convention)) > 0)
);
-- statement-break
CREATE INDEX ix_curve_points_etl_run_id ON curve_points (etl_run_id);
