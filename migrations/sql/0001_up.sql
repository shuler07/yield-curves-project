CREATE TABLE etl_runs (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    run_type VARCHAR(16) NOT NULL,
    date_from DATE NOT NULL,
    date_to DATE NOT NULL,
    started_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    finished_at TIMESTAMPTZ,
    status VARCHAR(24) DEFAULT 'running' NOT NULL,
    rows_processed INTEGER DEFAULT 0 NOT NULL,
    rows_saved INTEGER DEFAULT 0 NOT NULL,
    reason TEXT,
    error TEXT,
    CONSTRAINT ck_etl_runs_type CHECK (run_type IN ('manual', 'scheduled')),
    CONSTRAINT ck_etl_runs_status CHECK (status IN (
        'running', 'success', 'partial_success', 'failed', 'skipped_calendar', 'no_data'
    )),
    CONSTRAINT ck_etl_runs_date_range CHECK (date_from <= date_to),
    CONSTRAINT ck_etl_runs_counts CHECK (rows_processed >= 0 AND rows_saved >= 0),
    CONSTRAINT ck_etl_runs_times CHECK (finished_at IS NULL OR finished_at >= started_at),
    CONSTRAINT ck_etl_runs_finished CHECK (
        (status = 'running' AND finished_at IS NULL) OR
        (status <> 'running' AND finished_at IS NOT NULL)
    ),
    CONSTRAINT ck_etl_runs_reason CHECK (
        status NOT IN ('skipped_calendar', 'no_data') OR
        (reason IS NOT NULL AND length(btrim(reason)) > 0)
    ),
    CONSTRAINT ck_etl_runs_error CHECK (
        status NOT IN ('failed', 'partial_success') OR
        (error IS NOT NULL AND length(btrim(error)) > 0)
    )
);
-- statement-break
CREATE INDEX ix_etl_runs_started_at ON etl_runs (started_at);
-- statement-break
CREATE INDEX ix_etl_runs_status_started_at ON etl_runs (status, started_at);
