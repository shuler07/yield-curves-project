CREATE TABLE stress_shocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario VARCHAR(32) NOT NULL,
    version VARCHAR(64) NOT NULL,
    parameters JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT uq_stress_shocks_scenario_version UNIQUE (scenario, version),
    CONSTRAINT ck_stress_shocks_scenario CHECK (scenario IN (
        'Parallel_Up', 'Parallel_Down', 'Short_Up', 'Short_Down', 'Steepener', 'Flattener'
    )),
    CONSTRAINT ck_stress_shocks_version CHECK (length(btrim(version)) > 0),
    CONSTRAINT ck_stress_shocks_parameters CHECK (
        jsonb_typeof(parameters) = 'object' AND parameters <> '{}'::jsonb
    )
);
