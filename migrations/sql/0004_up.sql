INSERT INTO raw_curve_points (curve_date, quote_time, tenor, yield_rate, etl_run_id, created_at)
SELECT curve_date, quote_time, tenor, yield_rate, etl_run_id, created_at FROM curve_points
WHERE NOT is_interpolated AND NOT is_extrapolated
AND tenor IN (0.25, 0.5, 0.75, 1, 2, 3, 4, 5, 7, 10, 15, 20);
-- statement-break
INSERT INTO processed_curve_points (curve_date, quote_time, tenor, scenario, scenario_version,
yield_rate, discount_factor, etl_run_id, created_at, is_interpolated, is_extrapolated, is_deleted)
SELECT curve_date, quote_time, tenor, 'Baseline', NULL, yield_rate, discount_factor, etl_run_id,
created_at, is_interpolated, is_extrapolated, is_deleted FROM curve_points;
-- statement-break
INSERT INTO processed_curve_points (curve_date, quote_time, tenor, scenario, scenario_version,
yield_rate, discount_factor, etl_run_id, created_at, is_interpolated, is_extrapolated, is_deleted)
SELECT p.curve_date, p.quote_time, p.tenor, s.scenario, s.version, c.stressed_yield,
c.discount_factor, c.etl_run_id, c.created_at, p.is_interpolated, p.is_extrapolated, p.is_deleted
FROM stress_curves c JOIN curve_points p ON p.id = c.curve_point_id
JOIN stress_shocks s ON s.id = c.stress_shock_id;
