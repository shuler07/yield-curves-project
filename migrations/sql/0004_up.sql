CREATE TABLE raw_curve_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    curve_date DATE NOT NULL,
    quote_time TIME WITHOUT TIME ZONE NOT NULL,
    tenor NUMERIC(12, 6) NOT NULL,
    yield_rate NUMERIC NOT NULL,
    etl_run_id UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_raw_curve_points_snapshot_tenor UNIQUE (curve_date, quote_time, tenor),
    CONSTRAINT ck_raw_curve_points_tenor CHECK (tenor > 0 AND tenor < 'Infinity'::numeric),
    CONSTRAINT ck_raw_curve_points_yield CHECK (yield_rate > '-Infinity'::numeric AND yield_rate < 'Infinity'::numeric),
    CONSTRAINT fk_raw_curve_points_etl_run FOREIGN KEY(etl_run_id) REFERENCES etl_runs (id) ON DELETE RESTRICT
);
-- statement-break
CREATE INDEX ix_raw_curve_points_etl_run_id ON raw_curve_points (etl_run_id);
-- statement-break
CREATE TABLE processed_curve_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    curve_date DATE NOT NULL,
    quote_time TIME WITHOUT TIME ZONE NOT NULL,
    tenor NUMERIC(12, 6) NOT NULL,
    scenario VARCHAR(32) NOT NULL,
    scenario_version VARCHAR(64),
    yield_rate NUMERIC(18, 10) NOT NULL,
    discount_factor NUMERIC(28, 18) NOT NULL,
    etl_run_id UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    is_interpolated BOOLEAN DEFAULT false NOT NULL,
    is_extrapolated BOOLEAN DEFAULT false NOT NULL,
    is_deleted BOOLEAN DEFAULT false NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_processed_curve_points_key UNIQUE NULLS NOT DISTINCT (curve_date, quote_time, tenor, scenario, scenario_version),
    CONSTRAINT fk_processed_curve_points_scenario FOREIGN KEY(scenario, scenario_version) REFERENCES stress_shocks (scenario, version) ON DELETE RESTRICT,
    CONSTRAINT ck_processed_curve_points_scenario CHECK (scenario IN ('Baseline', 'Parallel_Up', 'Parallel_Down', 'Short_Up', 'Short_Down', 'Steepener', 'Flattener')),
    CONSTRAINT ck_processed_curve_points_version CHECK ((scenario = 'Baseline' AND scenario_version IS NULL) OR (scenario <> 'Baseline' AND scenario_version IS NOT NULL)),
    CONSTRAINT ck_processed_curve_points_tenor CHECK (tenor > 0 AND tenor < 'Infinity'::numeric),
    CONSTRAINT ck_processed_curve_points_yield CHECK (yield_rate > '-Infinity'::numeric AND yield_rate < 'Infinity'::numeric),
    CONSTRAINT ck_processed_curve_points_discount CHECK (discount_factor > 0 AND discount_factor < 'Infinity'::numeric),
    CONSTRAINT fk_processed_curve_points_etl_run FOREIGN KEY(etl_run_id) REFERENCES etl_runs (id) ON DELETE RESTRICT
);
-- statement-break
CREATE INDEX ix_processed_curve_points_etl_run_id ON processed_curve_points (etl_run_id);
-- statement-break
CREATE INDEX ix_processed_curve_points_scenario ON processed_curve_points (scenario, scenario_version, curve_date, quote_time, tenor);
